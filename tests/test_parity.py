"""PER-239 — the bindings must reproduce the engine, exactly.

The reference in `ic_golden.json` was produced BY the engine
(`tools/gen_ic_golden.cpp` linking `qe::qe`), not by a second
implementation written in Python to check the first one. That is the
PER-221 posture: the gbdt parity test asserts against xgboost's own
output rather than against a second Python walk of the model, because
two implementations that agree may simply share a bug.

The golden carries its input as well as its output, so this test never
has to reproduce a random stream. A shared RNG that drifts between
languages turns a parity test into a coincidence test.

Exact equality, not `approx`. The binding does no arithmetic — it moves
doubles across a boundary. A tolerance here would hide the only kind of
bug this test can catch.
"""

import json
import pathlib
import unittest

import qe

GOLDEN = pathlib.Path(__file__).with_name("ic_golden.json")

SCALARS = [
    "n_bars", "n_symbols", "horizon", "ts_ic_mean", "ts_ic_std", "xs_ic_mean",
    "xs_ic_std", "xs_ic_t_stat", "xs_ic_se_nw", "xs_ic_nw_lag", "xs_ic_t_stat_nw",
    "xs_ic_t_stat_nonoverlap", "xs_ic_nonoverlap_phases", "n_obs",
]


class IcParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.g = json.loads(GOLDEN.read_text())
        cls.r = qe.ic_analysis(
            factor=cls.g["input"]["factor"],
            returns=cls.g["input"]["returns"],
            horizon=cls.g["input"]["horizon"],
        )

    def test_golden_came_from_the_engine_we_built_against(self):
        # A golden generated by a different engine than the one linked
        # here would make every assertion below meaningless-but-green.
        self.assertEqual(self.g["engine_version"], qe.engine_version)

    def test_the_golden_is_not_degenerate(self):
        # n_obs == 0 is `ic_analysis`'s answer for a shape mismatch, and
        # a golden of all-zeros would pass every comparison below while
        # testing nothing.
        self.assertGreater(self.g["expected"]["n_obs"], 300)
        self.assertNotEqual(self.g["expected"]["xs_ic_mean"], 0.0)

    def test_scalars_match_exactly(self):
        for f in SCALARS:
            with self.subTest(field=f):
                self.assertEqual(getattr(self.r, f), self.g["expected"][f])

    def test_vectors_match_exactly(self):
        self.assertEqual(list(self.r.xs_ic_series), self.g["expected"]["xs_ic_series"])
        self.assertEqual(list(self.r.ts_index), self.g["expected"]["ts_index"])


if __name__ == "__main__":
    unittest.main(verbosity=2)


class RollingIcParity(unittest.TestCase):
    """PER-243 — rolling IC, same golden, same exactness."""

    @classmethod
    def setUpClass(cls):
        cls.g = json.loads(GOLDEN.read_text())
        p = cls.g["rolling"]["params"]
        cls.r = qe.rolling_ic_analysis(
            factor=cls.g["input"]["factor"],
            returns=cls.g["input"]["returns"],
            timestamps=cls.g["input"]["timestamps"],
            horizon=cls.g["input"]["horizon"],
            window_bars=p["window_bars"],
            step_bars=p["step_bars"],
        )

    def test_not_degenerate(self):
        # An empty `windows` is how this function reports a shape
        # mismatch. A golden of zero windows would pass everything below.
        self.assertGreater(self.g["rolling"]["expected"]["n_windows"], 5)

    def test_scalars(self):
        e = self.g["rolling"]["expected"]
        for f in ("n_bars", "horizon", "window_bars", "step_bars"):
            with self.subTest(field=f):
                self.assertEqual(getattr(self.r, f), e[f])
        self.assertEqual(len(self.r.windows), e["n_windows"])

    def test_every_window_matches_exactly(self):
        for i, (got, want) in enumerate(zip(self.r.windows, self.g["rolling"]["windows"])):
            for f, v in want.items():
                with self.subTest(window=i, field=f):
                    self.assertEqual(getattr(got, f), v)


